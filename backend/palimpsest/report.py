"""Research-report export (Markdown + CSV) built from analysis results.

Results usually arrive here after a JSON round trip through the browser, where
NaN has become ``null``; every number is therefore formatted through ``_fmt``,
which renders missing values as "-" instead of failing.
"""
from __future__ import annotations

import io
import json
import math

import pandas as pd

from . import config as C


def _fmt(v, nd: int = 3) -> str:
    if v is None:
        return "-"
    if isinstance(v, bool):
        return str(v)
    if isinstance(v, (int, float)):
        return f"{v:.{nd}f}" if math.isfinite(v) else "-"
    try:
        f = float(v)
        return f"{f:.{nd}f}" if math.isfinite(f) else "-"
    except (TypeError, ValueError):
        return str(v)


def _pct(v, nd: int = 1) -> str:
    return "-" if v is None else f"{_fmt(100 * float(v), nd)}%"


def _label(el: str) -> str:
    return C.CHEM_LABELS.get(el, el)


def _round(o, nd: int = 3):
    """Round numbers inside (possibly nested) dicts/lists for compact display."""
    if isinstance(o, dict):
        return {k: _round(v, nd) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_round(v, nd) for v in o]
    if isinstance(o, float):
        return round(o, nd) if math.isfinite(o) else None
    return o


def _cell(v) -> str:
    """Markdown table cell: escape pipes and newlines."""
    return str(v).replace("|", "\\|").replace("\n", " ")


def _provenance_md(p: dict | None) -> str:
    if not p:
        return "## Reproducibility\n\nNo provenance block was attached to this result."
    lines = ["## Reproducibility", "", f"- Software: {p.get('software', '-')}",
             f"- Generated: {p.get('timestamp_utc', '-')}", f"- Parameter hash: `{p.get('hash', '-')}`"]
    for k, v in (p.get("data") or {}).items():
        lines.append(f"- Data ({k.replace('_', ' ')}): {v}")
    lines.append(f"- Sample selection: `{json.dumps(p.get('selection'))}`")
    lines.append(f"- Parallax zero-point: {p.get('parallax_zero_point', '-')}")
    lines.append(f"- Solar motion (U,V,W) = {p.get('solar_motion_UVW_kms')} km/s; z_sun = {p.get('solar_height_kpc')} kpc")
    lines.append(f"- Chemical systematic floor (dex): `{json.dumps(_round(p.get('chemistry_floor_dex')))}`")
    lines.append(f"- Parameters: `{json.dumps(p.get('parameters'), default=str)}`")
    lines += ["", "To reproduce: rebuild the dataset with `python scripts/build_dataset.py`, start the API, and repeat "
                  "the operation with the parameters above (see README)."]
    return "\n".join(lines)


def _list(title: str, items) -> list[str]:
    items = list(items or [])
    return ["", f"## {title}", ""] + ([f"- {s}" for s in items] if items else ["- none"])


def group_report(ev: dict, title: str = "Candidate stellar family") -> str:
    h = ev["hypotheses"]
    out = [f"# {title}", "",
           "> Generated by Palimpsest. Measured quantities, model-dependent inferences and hypotheses are "
           "separated below. Nothing here is a confirmed discovery.", "",
           "## Hypotheses", "", f"- **A**: {h['A']}", f"- **B**: {h['B']}", "",
           f"**Assessment:** {h['verdict']}", "",
           "| Evidence | Value | A predicts | B predicts | Favours |", "|---|---|---|---|---|"]
    for r in h["rows"]:
        out.append("| " + " | ".join(_cell(r.get(k, "-")) for k in ("evidence", "value", "A_predicts", "B_predicts",
                                                                       "favours")) + " |")
    members = ev.get("members") or []
    out += ["", f"## Members ({ev.get('n', len(members))})", "",
            "| Gaia DR3 source_id | APOGEE ID | d [pc] | Teff [K] | log g | [Fe/H] | OCCAM |",
            "|---|---|---|---|---|---|---|"]
    for m in members:
        out.append(f"| {m.get('source_id')} | {m.get('apogee_id', '')} | {_fmt(m.get('dist_pc'), 0)} | "
                   f"{_fmt(m.get('teff'), 0)} | {_fmt(m.get('logg'), 2)} | {_fmt(m.get('feh'), 2)} | {m.get('occam') or ''} |")
    k = ev.get("kinematics") or {}
    vd = k.get("velocity_dispersion") or {}
    sig = lambda c: _fmt((vd.get(c) or {}).get("sigma_int"), 2)
    cen = k.get("centroid_pc") or []
    out += ["", "## Kinematics (measured -> derived)", "",
            f"- Centroid (X,Y,Z) = ({', '.join(_fmt(v, 0) for v in cen)}) pc; median size {_fmt(k.get('size_pc'), 1)} pc",
            f"- Intrinsic velocity dispersion: U {sig('U')}, V {sig('V')}, W {sig('W')} km/s "
            f"(3D {_fmt(vd.get('sigma_3d'), 2)} km/s)",
            f"- Median distance uncertainty: {_fmt(k.get('median_distance_error_pc'), 1)} pc"]
    ch = ev.get("chemistry") or {}
    out += ["", "## Chemistry (APOGEE DR17)", ""]
    if ch.get("available"):
        null = ch.get("null_lnBF") or {}
        ref = ch.get("reference") or {}
        out += [f"- ln Bayes factor (single birth cloud vs independent field draws): **{_fmt(ch.get('ln_bayes_factor'), 2)}**"]
        if ch.get("stratification"):
            out.append(f"- Stratification: {ch['stratification']}")
        for cls, b in (ch.get("by_class") or {}).items():
            ref_c = b.get("reference") or {}
            out.append(f"  - {cls}s: n={b.get('n')}, ln BF = {_fmt(b.get('ln_bayes_factor'), 2)}, "
                       f"reference {ref_c.get('n', '-')} field {cls}s")
        out += [
                f"- Null distribution from {len(null.get('values') or [])} random field groups of the same size: "
                f"median {_fmt(null.get('median'), 2)}, 99th percentile {_fmt(null.get('p99'), 2)}; "
                f"empirical false-positive rate {_fmt(ch.get('empirical_false_positive_rate'), 3)}",
                f"- Reference population: {ref.get('n', '-')} stars with Teff {ref.get('teff')}, "
                f"log g {ref.get('logg')}, R {ref.get('R_kpc')} kpc", "",
                "| Element | n | mean | intrinsic scatter | 95% UL | median error | field spread | delta lnBF (element) |",
                "|---|---|---|---|---|---|---|---|"]
        contrib = {c["element"]: c.get("delta_lnBF") for c in ch.get("element_contributions") or []}
        spread = ch.get("reference_spread") or {}
        for e in ch.get("elements") or []:
            el = e["element"]
            out.append(f"| {_label(el)} | {e.get('n', '-')} | {_fmt(e.get('mean'))} | {_fmt(e.get('sigma_int'))} | "
                       f"{_fmt(e.get('sigma_int_upper95'))} | {_fmt(e.get('median_err'))} | {_fmt(spread.get(el))} | "
                       f"{_fmt(contrib.get(el), 2)} |")
    else:
        out.append(f"Not evaluated: {ch.get('reason', 'no chemistry result')}")
    tb = ev.get("traceback")
    if tb:
        smin, tmin = tb.get("size_min_pc") or {}, tb.get("t_min_myr") or {}
        out += ["", f"## Traceback ({tb.get('potential', '-')}, {tb.get('n_mc', '-')} Monte Carlo realisations)", "",
                f"- Present size {_fmt(tb.get('size_now_pc'), 1)} pc; minimum size {_fmt(smin.get('median'), 1)} pc "
                f"[{_fmt(smin.get('p16'), 1)}-{_fmt(smin.get('p84'), 1)}] at {_fmt(tmin.get('median'), 1)} Myr "
                f"[{_fmt(tmin.get('p16'), 1)}, {_fmt(tmin.get('p84'), 1)}]",
                f"- Fraction of realisations with minimum at the present: {_fmt(tb.get('fraction_min_at_present'), 2)}"]
    ag = ev.get("ages") or {}
    out += ["", "## Ages", "",
            (f"- {ag.get('n')} giants; median {_fmt(ag.get('median_age_gyr'), 2)} Gyr; intrinsic log-age scatter "
             f"{_fmt(ag.get('log_age_sigma_int'), 2)} dex. {ag.get('note', '')}" if ag.get("available")
             else f"- Not evaluated: {ag.get('reason', 'insufficient data')}")]
    gc = ev.get("galah_check") or {}
    if gc.get("available"):
        out += ["", "## Independent survey check (GALAH DR4, own abundance scale)", ""] + \
               [f"- {e.get('element')}: n={e.get('n')}, intrinsic scatter {_fmt(e.get('sigma_int'))} dex "
                f"(95% UL {_fmt(e.get('sigma_int_upper95'))})" for e in gc.get("elements") or []]
    kn = ev.get("known") or {}
    out += ["", "## Comparison with known populations", "",
            f"- OCCAM members among candidates: {kn.get('occam') or 'none'}"]
    for m in kn.get("hunt_reffert_2023") or []:
        out.append(f"- Hunt & Reffert (2023) {m.get('name')} ({m.get('type')}): centroid offset "
                   f"{_fmt(m.get('centroid_offset_pc'), 0)} pc, velocity offset {_fmt(m.get('velocity_offset_kms'), 1)} km/s, "
                   f"age {_fmt(m.get('age_myr'), 0)} Myr")
    out += _list("Suggested follow-up", ev.get("follow_up"))
    out += _list("Limitations", ev.get("caveats"))
    out += ["", _provenance_md(ev.get("provenance"))]
    return "\n".join(out)


def sibling_report(r: dict) -> str:
    c = r["counts"]
    out = [f"# Sibling search for Gaia DR3 {r['seed']}", "",
           "> Candidates are stars compatible with a shared birth site under the stated tests. Compatibility is "
           "not proof of common origin.", "",
           f"Assumed birth velocity dispersion: {_fmt(r.get('birth_velocity_dispersion_kms'), 1)} km/s", "",
           "## Counts", "",
           f"- Comparable stars: {c.get('comparable_stars')}",
           f"- Chemically compatible: {c.get('chemically_compatible')}",
           f"- Dynamically compatible (actions): {c.get('dynamically_compatible')}",
           f"- Both: {c.get('both')} (expected if independent: {_fmt(c.get('expected_both_if_independent'), 1)})",
           "", "## Method", ""] + [f"- **{k}**: {v}" for k, v in (r.get("method") or {}).items()]
    out += ["", "## Candidates", "",
            "| source_id | actions M^2 | chem chi2/dof | chem p | separation [pc] | dv [km/s] |", "|---|---|---|---|---|---|"]
    for x in (r.get("candidates") or [])[:50]:
        out.append(f"| {x.get('source_id')} | {_fmt(x.get('mahalanobis2_actions'), 2)} | {_fmt(x.get('chem_chi2'), 1)}/"
                   f"{x.get('chem_dof')} | {_fmt(x.get('chem_p'), 3)} | {_fmt(x.get('separation_pc'), 0)} | "
                   f"{_fmt(x.get('dv_kms'), 1)} |")
    if r.get("traceback"):
        out += ["", "## Past proximity (Monte Carlo traceback)", "",
                "| source_id | d_min [pc] (16-84%) | t_min [Myr] |", "|---|---|---|"]
        for t in r["traceback"]:
            d = t.get("d_min_pc") or {}
            out.append(f"| {t.get('source_id')} | {_fmt(d.get('median'), 0)} ({_fmt(d.get('p16'), 0)}-"
                       f"{_fmt(d.get('p84'), 0)}) | {_fmt(t.get('t_min_myr'), 1)} |")
    out += _list("Limitations", r.get("caveats"))
    out += ["", _provenance_md(r.get("provenance"))]
    return "\n".join(out)


def encounter_report(r: dict) -> str:
    cl = r.get("cluster") or {}
    res = r.get("result") or {}
    ctrl = r.get("control") or {}
    d, t, v = res.get("d_min_pc") or {}, res.get("t_min_myr") or {}, res.get("v_rel_kms") or {}
    out = [f"# Ejection test: Gaia DR3 {r['source_id']} and {cl.get('name', '?')}", "",
           r.get("interpretation", ""), "",
           "## Result", "",
           f"- Encounter radius: {_fmt(r.get('radius_pc'), 1)} pc; look-back {_fmt(r.get('lookback_myr'), 0)} Myr; "
           f"{r.get('n_mc')} Monte Carlo realisations",
           f"- Closest approach: {_fmt(d.get('median'), 1)} pc (16-84%: {_fmt(d.get('p16'), 1)}-{_fmt(d.get('p84'), 1)})",
           f"- Epoch: {_fmt(t.get('median'), 2)} Myr (16-84%: {_fmt(t.get('p16'), 2)} to {_fmt(t.get('p84'), 2)})",
           f"- Relative speed at closest approach: {_fmt(v.get('median'), 1)} km/s",
           f"- Fraction of realisations within the radius: {_pct(res.get('fraction_within_radius'))}",
           f"- Control ({ctrl.get('n', 0)} field stars at similar distance): mean fraction "
           f"{_pct(ctrl.get('mean_fraction_within_radius'))}",
           f"- Cluster: age {_fmt(cl.get('age_myr'), 0)} Myr, distance {_fmt(cl.get('distance_pc'), 0)} pc, "
           f"tidal radius {_fmt(cl.get('rt_pc'), 1)} pc (Hunt & Reffert 2023)"]
    out += _list("Limitations", r.get("caveats"))
    out += ["", _provenance_md(r.get("provenance"))]
    return "\n".join(out)


CSV_COLS = ["source_id", "APOGEE_ID", "ra", "dec", "parallax", "parallax_error", "zpt_used", "pmra", "pmra_error",
            "pmdec", "pmdec_error", "rv", "rv_error", "ruwe", "dist_pc", "X", "Y", "Z", "U", "V", "W", "TEFF", "LOGG",
            "E", "Lz", "J_R", "J_z", "ecc", "zmax", "age_gyr"]


def members_csv(stars: pd.DataFrame, source_ids: list) -> str:
    cols = CSV_COLS + [c for el in C.CHEM_ELEMENTS for c in (el, el + "_ERR")]
    cols = [c for c in cols if c in stars.columns]
    want = [str(s).strip() for s in source_ids]
    key = stars["source_id_str"] if "source_id_str" in stars else stars["source_id"].astype(str)
    d = stars[key.isin(want)][cols]
    buf = io.StringIO()
    buf.write("# Palimpsest member export: APOGEE DR17 x Gaia DR3; distances = 1/(parallax - zpt_used); "
              "orbital quantities in the McMillan (2017) potential\n")
    d.to_csv(buf, index=False, float_format="%.6g")
    return buf.getvalue()
